def _npm_package_name(import_path: str) -> str | None:
    """
    Extract the installable npm package name from an import path.

    '@hookform/resolvers/zod' → '@hookform/resolvers'
    '@radix-ui/react-dialog' → '@radix-ui/react-dialog'
    'react-hook-form'        → 'react-hook-form'
    './components/Foo'       → None  (relative)
    '@/services/api'         → None  (path alias)
    'path'                   → None  (Node.js built-in)
    """
    if not import_path:
        return None
    for prefix in _INTERNAL_PREFIXES:
        if import_path.startswith(prefix):
            return None
    if import_path.startswith("@"):
        parts = import_path.split("/")
        pkg = f"{parts[0]}/{parts[1]}" if len(parts) >= 2 else import_path
        # Filter out internal @/ aliases that slipped through
        if pkg.startswith("@/"):
            return None
        return pkg
    name = import_path.split("/")[0]
    if name in _NODE_BUILTINS:
        return None
    return name


def extract_npm_imports(content: str) -> Set[str]:
    """Return all npm package names imported in a TS/TSX file."""
    packages: Set[str] = set()
    for m in _NPM_IMPORT_RE.finditer(content):
        pkg = _npm_package_name(m.group(1))
        if pkg:
            packages.add(pkg)
    return packages


def extract_python_imports(content: str) -> Set[str]:
    """Return all third-party pip package names imported in a Python file."""
    packages: Set[str] = set()
    for m in _PY_IMPORT_RE.finditer(content):
        module = m.group(1) or m.group(2)
        if not module:
            continue
        top = module.split(".")[0]
        if top in _PYTHON_STDLIB:
            continue
        packages.add(_PY_IMPORT_TO_PIP.get(top, top))
    return packages


def _declared_npm(package_json_content: str) -> Set[str]:
    try:
        pkg = json.loads(package_json_content)
    except Exception:
        return set()
    declared: Set[str] = set()
    declared.update(pkg.get("dependencies", {}).keys())
    declared.update(pkg.get("devDependencies", {}).keys())
    return declared


def _declared_pip(requirements_content: str) -> Set[str]:
    declared: Set[str] = set()
    for line in requirements_content.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        pkg = re.split(r"[>=<!~\[\s]", line)[0].strip().lower()
        if pkg:
            declared.add(pkg)
    return declared


def scan_flat_files(flat_files: List[dict]) -> dict:
    """
    Scan a list of {"path": str, "content": str} dicts.

    Returns:
      {
        "npm_imports":   set of all npm packages found in TS/TSX files,
        "pip_imports":   set of all pip packages found in .py files,
        "npm_missing":   list of packages imported but not in package.json,
        "pip_missing":   list of packages imported but not in requirements.txt,
        "package_json_raw":    str | None,
        "requirements_raw":    str | None,
      }
    """
    npm_imports: Set[str] = set()
    pip_imports: Set[str] = set()
    package_json_raw: str | None = None
    requirements_raw: str | None = None

    for f in flat_files:
        path: str = f.get("path", "")
        content: str = f.get("content", "") or ""

        if path == "frontend/package.json":
            package_json_raw = content
        elif path == "backend/requirements.txt":
            requirements_raw = content
        elif path.startswith("frontend/") and path.endswith((".ts", ".tsx")):
            npm_imports.update(extract_npm_imports(content))
        elif path.startswith("backend/") and path.endswith(".py"):
            pip_imports.update(extract_python_imports(content))

    declared_npm = _declared_npm(package_json_raw or "{}")
    declared_pip = _declared_pip(requirements_raw or "")

    npm_missing = [p for p in npm_imports if p not in declared_npm]
    pip_missing = [p for p in pip_imports if p.lower() not in declared_pip]

    return {
        "npm_imports":       npm_imports,
        "pip_imports":       pip_imports,
        "npm_missing":       npm_missing,
        "pip_missing":       pip_missing,
        "package_json_raw":  package_json_raw,
        "requirements_raw":  requirements_raw,
    }
