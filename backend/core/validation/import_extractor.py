# Matches: import X from 'pkg', import 'pkg', from 'pkg' import X
_NPM_IMPORT_RE = re.compile(
    r"""(?:import|from)\s+['"](@?[a-zA-Z0-9][a-zA-Z0-9\-._]*(?:/[a-zA-Z0-9][a-zA-Z0-9\-._]*)*)['"]""",
    re.MULTILINE,
)

# Matches: import X, from X import Y (top-level only)
_PY_IMPORT_RE = re.compile(
    r"^(?:import\s+([\w.]+)|from\s+([\w.]+)\s+import)",
    re.MULTILINE,
)

